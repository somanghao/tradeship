export function iconSprite(kind) {
  const fn = DRAW[kind];
  if (!fn) throw new Error(`unknown icon: ${kind}`);
  return bake(`icon:${kind}`, S, S, (g, ctx) => {
    fn(g);
    outline(ctx, S, S);
  });
}

