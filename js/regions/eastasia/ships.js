// ★ hull은 `js/sprites/ship.js: HULLS`의 키여야 그림이 뜬다. **정크·아타케부네·판옥선의
//   선형은 아직 없다.** 실루엣이 가장 가까운 것을 빌려 쓰고 무엇이 달라야 하는지는
//   근거 JSON의 art.hullTodo에 적었다.
