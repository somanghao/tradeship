//   바다에서 결정적이다) 세로돛이라 맞바람에 유럽 가로돛보다 낫다. 그래서 이 파일의
//   정크 계열은 **rig가 0.15**로 낮다 — 라틴세일 쪽에 가깝다는 뜻이다.
//   일본의 아타케부네·세키부네는 반대로 **네모돛 한 장 + 노**라 rig가 높으면서도 느리다.
