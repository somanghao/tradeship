//   전에 전부 null이었던 것은 빌린 깃발(venice·hafsid·genoa)을 쓰면 **베네치아에서
//   복선을, 튀니스에서 판옥선을 싸게 짓게 되기 때문**이었다(그 깃발을 단 항구는 요구등급 −1).
//   ※ geo.js의 도시 깃발도 제 깃발로 배선됐다 — 이제 광저우·취안저우에서 복선이,
//     사카이·하카타에서 일본 배가, 부산포에서 판옥선과 거북선이 한 등급 싸게 나온다.
