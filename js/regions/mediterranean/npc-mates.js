//   wage     일당. **선원 일당 2.4닢이 기준자**이고 부관 에이미가 2.6이다.
//              선장급 3~6 · 기능직 2.8~4
//   cut      성과 배분(0~0.06). **선장급만 갖는다**(에이미는 0.11)
//   perks    아래 열 키만 쓴다. 다른 키를 만들면 규칙이 조용히 무시한다:
//              sailDaysOff 항해일수 −n    gunUp 포격 +n        meleeUp 백병 +n
//              hullUp 선체최대 +n         repairOff 수리비 −n   upkeepOff 유지비 −n
//              tariffOff 입항세 −n        impactOff 시장압력 −n
//              fleeUp 도주 +n             crewLossOff 전투사상 −n
