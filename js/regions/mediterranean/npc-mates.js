//   lines    { greet, hire, refuse, aboard, leave } — 만남 · 계약 · 거절 · 승선 · 이별
//
// ★ **그 바다의 제도와 직업을 인물로 보여줘라.** 근거는 근거 JSON에 적는다.
//   보수(hire·wage·cut)는 사료가 아니라 **밸런스 값**이므로 근거 JSON에서 갈라 적는다.

